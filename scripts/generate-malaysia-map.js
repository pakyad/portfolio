/* eslint-disable @typescript-eslint/no-require-imports */
const fs = require("fs");
const path = require("path");
const { geoMercator, geoPath, geoContains } = require("d3-geo");
const { feature } = require("topojson-client");

const WORLD_URL =
  "https://cdn.jsdelivr.net/npm/world-atlas@2/countries-110m.json";

const PENANG_LON = 100.3288;
const PENANG_LAT = 5.4141;

async function main() {
  console.log("Fetching world atlas…");
  const res = await fetch(WORLD_URL);
  const world = await res.json();

  const countries = feature(world, world.objects.countries);
  const malaysia = countries.features.find(
    (f) => f.properties.name === "Malaysia"
  );

  if (!malaysia) {
    console.error("Malaysia not found in world data");
    process.exit(1);
  }

  const W = 800;
  const H = 600;
  const projection = geoMercator().fitSize([W, H], malaysia);
  const pathGen = geoPath(projection);
  const [[x0, y0], [x1, y1]] = pathGen.bounds(malaysia);

  const SPACING = 12;
  const DOT_R = 3.5;
  const dots = [];

  for (let x = Math.floor(x0); x <= Math.ceil(x1); x += SPACING) {
    for (let y = Math.floor(y0); y <= Math.ceil(y1); y += SPACING) {
      const pt = projection.invert([x, y]);
      if (geoContains(malaysia, pt)) {
        dots.push({ x, y });
      }
    }
  }

  console.log(`${dots.length} dots generated`);

  const penang = projection([PENANG_LON, PENANG_LAT]);
  console.log(`Penang at (${penang[0].toFixed(1)}, ${penang[1].toFixed(1)})`);

  const dotElements = dots
    .map((d) => `<circle cx="${d.x.toFixed(1)}" cy="${d.y.toFixed(1)}" r="${DOT_R}"/>`)
    .join("\n    ");

  const penangR = DOT_R + 1.5;
  const labelX = penang[0] + 12;
  const labelY = penang[1] + 1;

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" class="location-map-svg">
  <g fill="rgba(247,245,240,0.12)">
    ${dotElements}
  </g>
  <circle cx="${penang[0].toFixed(1)}" cy="${penang[1].toFixed(1)}" r="${penangR + 1.5}" fill="none" stroke="#e8c87a" stroke-width="1" opacity="0.5"/>
  <circle cx="${penang[0].toFixed(1)}" cy="${penang[1].toFixed(1)}" r="${penangR}" fill="#e8c87a"/>
  <text x="${labelX.toFixed(1)}" y="${labelY.toFixed(1)}" fill="#e8c87a" font-family="monospace" font-size="12" dominant-baseline="middle">Penang</text>
</svg>`;

  const positions = JSON.stringify(dots);

  const tsx = `// Auto-generated by scripts/generate-malaysia-map.js — do not edit

export const MALAYSIA_MAP_SVG = \`${svg.replace(/`/g, "\\`")}\`;

export const DOT_POSITIONS: { x: number; y: number }[] = ${positions};

export const PENANG = { x: ${penang[0].toFixed(1)}, y: ${penang[1].toFixed(1)} };
`;

  const outDir = path.join(__dirname, "../src/components/home");
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, "generated-map.tsx"), tsx, "utf-8");

  console.log("Written to src/components/home/generated-map.tsx");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
